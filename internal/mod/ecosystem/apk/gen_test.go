// extractAPKINDEXText находит файл APKINDEX в tar-потоке и возвращает его
// текст (для проверок формата).
func extractAPKINDEXText(r io.Reader) (string, error) {
	tr := tar.NewReader(r)
	for {
		hdr, err := tr.Next()
		if err != nil {
			return "", err
		}
		base := hdr.Name
		if idx := strings.LastIndexByte(base, '/'); idx >= 0 {
			base = base[idx+1:]
		}
		if base == "APKINDEX" {
			b, _ := io.ReadAll(tr)
			return string(b), nil
		}
	}
}

// roundtrip: список .apk → APKINDEX.tar.gz → ParseAPKINDEX → те же F:.
func TestGenerateIndexesRoundtrip(t *testing.T) {
	t.Parallel()
	moment := time.Date(2026, 8, 24, 12, 0, 0, 0, time.UTC)
	storage := testutil.NewFakeStorage(testutil.FixedClock(moment))
	repo := domain.Repo{ID: 1, Name: "alice", Ecosystem: Name}
	putApk(t, storage, repo, "x86_64/apk-example-1.0-r0.apk",
		"pkgname = apk-example\npkgver = 1.0-r0\narch = x86_64\n")
	putApk(t, storage, repo, "x86_64/second-pkg-2.0-r1.apk",
		"pkgname = second-pkg\npkgver = 2.0-r1\narch = x86_64\n")

	g := &Generator{}
	if err := g.GenerateIndexes(context.Background(), repo, storage, nil); err != nil {
		t.Fatalf("GenerateIndexes: %v", err)
	}

	idxGz := readStorage(t, storage, "repo/1/apk/x86_64/apkindex.tar.gz")
	// ParseAPKINDEX сам разжимает gzip; передаём сырые байты.
	entries, err := collectIndex(ParseAPKINDEX(bytes.NewReader(idxGz)))
	if err != nil {
		t.Fatalf("ParseAPKINDEX roundtrip: %v", err)
	}
	paths := map[string]bool{}
	for _, e := range entries {
		paths[e.FilePath] = true
	}
	want := []string{
		"x86_64/apk-example-1.0-r0.apk",
		"x86_64/second-pkg-2.0-r1.apk",
	}
	for _, w := range want {
		if !paths[w] {
			t.Errorf("filepath %q отсутствует в APKINDEX (roundtrip): %+v", w, paths)
		}
	}
}

